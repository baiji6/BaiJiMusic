static uint32_t fstate(uint32_t state, const uint32_t key[6]) {
    uint32_t t1 =
        ((state & 1) << 31) | ((state & 0xf8000000) >> 1) | ((state & 0x1f800000) >> 3) |
        ((state & 0x01f80000) >> 5) | ((state & 0x001f8000) >> 7);
    uint32_t t2 =
        ((state & 0x0001f800) << 15) | ((state & 0x00001f80) << 13) | ((state & 0x000001f8) << 11) |
        ((state & 0x0000001f) << 9) | ((state & 0x80000000) >> 23);

    int k0 = (((t1 >> 24) & 0xff) ^ (key[0] & 0xff)) & 0xff;
    int k1 = (((t1 >> 16) & 0xff) ^ (key[1] & 0xff)) & 0xff;
    int k2 = (((t1 >> 8) & 0xff) ^ (key[2] & 0xff)) & 0xff;
    int k3 = (((t2 >> 24) & 0xff) ^ (key[3] & 0xff)) & 0xff;
    int k4 = (((t2 >> 16) & 0xff) ^ (key[4] & 0xff)) & 0xff;
    int k5 = (((t2 >> 8) & 0xff) ^ (key[5] & 0xff)) & 0xff;

    uint32_t st =
        ((uint32_t)SBOX[0][sboxBit(k0 >> 2)] << 28) |
        ((uint32_t)SBOX[1][sboxBit(((k0 & 0x03) << 4) | (k1 >> 4))] << 24) |
        ((uint32_t)SBOX[2][sboxBit(((k1 & 0x0f) << 2) | (k2 >> 6))] << 20) |
        ((uint32_t)SBOX[3][sboxBit(k2 & 0x3f)] << 16) |
        ((uint32_t)SBOX[4][sboxBit(k3 >> 2)] << 12) |
        ((uint32_t)SBOX[5][sboxBit(((k3 & 0x03) << 4) | (k4 >> 4))] << 8) |
        ((uint32_t)SBOX[6][sboxBit(((k4 & 0x0f) << 2) | (k5 >> 6))] << 4) |
        (uint32_t)SBOX[7][sboxBit(k5 & 0x3f)];

    st =
        (((st >> 16) & 1) << 31) | (((st >> 25) & 1) << 30) | (((st >> 12) & 1) << 29) | (((st >> 11) & 1) << 28) |
        (((st >> 3) & 1) << 27) | (((st >> 20) & 1) << 26) | (((st >> 4) & 1) << 25) | (((st >> 15) & 1) << 24) |
        (((st >> 31) & 1) << 23) | (((st >> 17) & 1) << 22) | (((st >> 9) & 1) << 21) | (((st >> 6) & 1) << 20) |
        (((st >> 27) & 1) << 19) | (((st >> 14) & 1) << 18) | (((st >> 1) & 1) << 17) | (((st >> 22) & 1) << 16) |
        (((st >> 30) & 1) << 15) | (((st >> 24) & 1) << 14) | (((st >> 8) & 1) << 13) | (((st >> 18) & 1) << 12) |
        (((st >> 0) & 1) << 11) | (((st >> 5) & 1) << 10) | (((st >> 29) & 1) << 9) | (((st >> 23) & 1) << 8) |
        (((st >> 13) & 1) << 7) | (((st >> 19) & 1) << 6) | (((st >> 2) & 1) << 5) | (((st >> 26) & 1) << 4) |
        (((st >> 10) & 1) << 3) | (((st >> 21) & 1) << 2) | (((st >> 28) & 1) << 1) | (((st >> 7) & 1) << 0);
    return st;
}

static void crypt_block(const uint8_t input[8], const uint32_t schedule[16][6], uint8_t output[8]) {
    uint32_t s0, s1;
    initialPermutation(input, &s0, &s1);
    for (int idx = 0; idx < 15; idx++) {
        uint32_t prev = s1;
        s1 = (fstate(s1, schedule[idx]) ^ s0);
        s0 = prev;
    }
    s0 = (fstate(s1, schedule[15]) ^ s0);
    inversePermutation(s0, s1, output);
}

static void key_schedule(const uint8_t key[8], int mode, uint32_t schedule[16][6]) {
    static const int keyRndShift[16] = {1,1,2,2,2,2,2,2,1,2,2,2,2,2,2,1};
    static const int keyPermC[28] = {
        56,48,40,32,24,16,8,0,57,49,41,33,25,17,9,1,58,50,42,34,26,18,10,2,59,51,43,35};
    static const int keyPermD[28] = {
        62,54,46,38,30,22,14,6,61,53,45,37,29,21,13,5,60,52,44,36,28,20,12,4,27,19,11,3};
    static const int keyCompression[48] = {
        13,16,10,23,0,4,2,27,14,5,20,9,22,18,11,3,25,7,15,6,26,19,12,1,
        40,51,30,36,46,54,29,39,50,44,32,47,43,48,38,55,33,52,45,41,49,35,28,31};

    uint32_t v0 = key[0] | (key[1] << 8) | (key[2] << 16) | (key[3] << 24);
    uint32_t v1 = key[4] | (key[5] << 8) | (key[6] << 16) | (key[7] << 24);

    uint32_t c = 0;
    for (int i = 0; i < 28; i++) {
        int b = keyPermC[i];
        int bit = b < 32 ? (int)((v0 >> (31 - b)) & 1) : (int)((v1 >> (63 - b)) & 1);
        c |= ((uint32_t)bit << (31 - i));
    }
    uint32_t d = 0;
    for (int i = 0; i < 28; i++) {
        int b = keyPermD[i];
        int bit = b < 32 ? (int)((v0 >> (31 - b)) & 1) : (int)((v1 >> (63 - b)) & 1);
        d |= ((uint32_t)bit << (31 - i));
    }

    for (int i = 0; i < 16; i++) {
        int sft = keyRndShift[i];
        c = (((c << sft) | (c >> (28 - sft))) & 0xfffffff0);
        d = (((d << sft) | (d >> (28 - sft))) & 0xfffffff0);
        int togen = (mode == 0) ? (15 - i) : i; /* DECRYPT=0 */
        for (int j = 0; j < 6; j++) schedule[togen][j] = 0;
        for (int j = 0; j < 24; j++) {
            int bit = (int)((c >> (31 - keyCompression[j])) & 1);
            schedule[togen][j >> 3] |= ((uint32_t)bit << (7 - (j & 7)));
        }
        for (int j = 24; j < 48; j++) {
            int bit = (int)((d >> (31 - (keyCompression[j] - 27))) & 1);
            schedule[togen][j >> 3] |= ((uint32_t)bit << (7 - (j & 7)));
        }
    }
}

qq_tripledes_key *qq_tripledes_key_new(const uint8_t key[24], int encrypt) {
    qq_tripledes_key *k = (qq_tripledes_key *)calloc(1, sizeof(qq_tripledes_key));
    if (!k) return NULL;
    if (encrypt) {
        key_schedule(key, 1, k->schedule);
        /* 3DES-EDE: encrypt key0, decrypt key1, encrypt key2 */
        /* We need three separate schedules; store in schedule[0..5]? */
    }
    /* For simplicity, we compute all three schedules and store in a flat layout.
       We allocate schedule as 3 * 16 * 6 below. */
    free(k);
    /* Reallocate with 3 groups */
    qq_tripledes_key *big = (qq_tripledes_key *)calloc(1, sizeof(qq_tripledes_key) * 3);
    if (!big) return NULL;
    /* big[0], big[1], big[2] */
    if (encrypt) {
        key_schedule(key, 1, big[0].schedule);
        key_schedule(key + 8, 0, big[1].schedule);
        key_schedule(key + 16, 1, big[2].schedule);
    } else {
        key_schedule(key + 16, 0, big[0].schedule);
        key_schedule(key + 8, 1, big[1].schedule);
        key_schedule(key, 0, big[2].schedule);
    }
    return big;
}

void qq_tripledes_key_free(qq_tripledes_key *k) {
    free(k);
}

void qq_tripledes_crypt_block(qq_tripledes_key *k, uint8_t block[8]) {
    uint8_t tmp[8];
    crypt_block(block, k[0].schedule, tmp);
    crypt_block(tmp, k[1].schedule, block);
    crypt_block(block, k[2].schedule, tmp);
    memcpy(block, tmp, 8);
}